from typing import TYPE_CHECKING, Protocol

if TYPE_CHECKING:
    from wechat_reply_agent.adapters.wechat.binding import RuntimeBinding

from wechat_reply_agent.domain.messages import (
    ConversationRef,
    Health,
    InboundEvent,
    LocalAttachment,
    SendIntent,
    SendResult,
)


class AdapterError(RuntimeError):
    """Public error codes only: never include desktop text or system exception payloads."""


class WechatAdapter(Protocol):
    def connect(self) -> dict: ...
    def close(self) -> None: ...
    def runtime_binding(self) -> "RuntimeBinding": ...
    def runtime_info(self) -> dict: ...
    def require_runtime_acceptance(self, binding) -> None: ...
    def prune_cache(self) -> int: ...
    def validate_text(self, text: str) -> None: ...
    def resolve_operation(self, outbox_id: str, resolution: str) -> None: ...
    def public_error(self, error: Exception) -> str: ...
    def health(self) -> Health: ...
    def poll_events(self, cursor: str | None = None) -> tuple[list[InboundEvent], str]: ...
    def acquire_attachment(self, event: InboundEvent) -> tuple[LocalAttachment, str | None]: ...
    def resolve_conversation(self, alias: str) -> ConversationRef: ...
    def send_text(self, intent: SendIntent) -> SendResult: ...
